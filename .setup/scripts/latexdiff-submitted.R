#!/usr/bin/env Rscript
# Marked manuscript: text added since the initial submission (MBR-26-107)
# highlighted, deletions not shown.
#
# Run from the project root inside the image, after `make latex` (it needs
# the knitted V2 in detritus/tex/):
#   apptainer exec ~/work/sif/docs.sif \
#     Rscript .setup/scripts/latexdiff-submitted.R
# It writes .setup/latex/manMetaVAR-manuscript-diff.Rtex (private, as every
# .Rtex; make latex knits it to detritus/tex/), which the drivers
# manMetaVAR-manuscript-marked-{blind,full}.tex input; run `make latex`
# again to build them.

root <- rprojroot::is_rstudio_project
detritus <- root$find_file("detritus", "tex")
submitted <- root$find_file(
  ".setup",
  "notes",
  "manuscript",
  "MBR-26-107",
  "manMetaVAR_manuscript_anonymous.Rtex"
)
final_v2 <- file.path(
  detritus,
  "manMetaVAR-manuscript-EDIT-THIS-V2.tex"
)
output <- root$find_file(
  ".setup",
  "latex",
  "manMetaVAR-manuscript-diff.Rtex"
)
stopifnot(file.exists(submitted), file.exists(final_v2))

# citation keys renamed after the submission (634ab86)
keys <- c(
  "Pesigan-Russell-Chow-2025o" = "Pesigan-Russell-Chow-2025a",
  "Moeyaert-Ugille-Beretvas-2017" = "Moeyaert-Ugille-Beretvas-etal-2017"
)

# resolve changes markup: \added{a} -> a, \deleted{a} -> "",
# \replaced{new}{old} -> new (balanced braces)
.Resolve <- function(text, cmd, nargs, keep) {
  pattern <- paste0("\\", cmd, "{")
  chars <- strsplit(text, "")[[1]]
  out <- character(0)
  i <- 1L
  n <- length(chars)
  repeat {
    rest <- paste(chars[i:n], collapse = "")
    j <- regexpr(pattern, rest, fixed = TRUE)
    if (j < 0) {
      out <- c(out, rest)
      break
    }
    out <- c(out, substr(rest, 1, j - 1))
    k <- i + j - 1L + nchar(pattern) - 1L
    args <- character(0)
    for (a in seq_len(nargs)) {
      depth <- 0L
      start <- k
      repeat {
        ch <- chars[k]
        if (ch == "\\") {
          k <- k + 2L
          next
        }
        if (ch == "{") depth <- depth + 1L
        if (ch == "}") {
          depth <- depth - 1L
          if (depth == 0L) break
        }
        k <- k + 1L
      }
      args <- c(args, paste(chars[(start + 1L):(k - 1L)], collapse = ""))
      k <- k + 1L
    }
    out <- c(out, keep(args))
    i <- k
    if (i > n) break
  }
  paste(out, collapse = "")
}

old_rtex <- file.path(detritus, "manMetaVAR-manuscript-submitted.Rtex")
old_tex <- file.path(detritus, "manMetaVAR-manuscript-submitted.tex")
new_tex <- file.path(detritus, "manMetaVAR-manuscript-final.tex")

old <- paste(readLines(submitted, warn = FALSE), collapse = "\n")
for (k in names(keys)) {
  old <- gsub(k, keys[[k]], old, fixed = TRUE)
}
writeLines(old, old_rtex)
knitr::knit(input = old_rtex, output = old_tex, envir = new.env(), quiet = TRUE)

new <- paste(readLines(final_v2, warn = FALSE), collapse = "\n")
new <- .Resolve(new, "replaced", 2L, function(x) x[1])
new <- .Resolve(new, "added", 1L, function(x) x[1])
new <- .Resolve(new, "deleted", 1L, function(x) "")
writeLines(new, new_tex)

diff <- system2(
  command = "latexdiff",
  args = c("--subtype=COLOR", "--math-markup=off", old_tex, new_tex),
  stdout = TRUE
)
# added text in color (from the COLOR subtype), no underline; deletions
# not shown
end <- grep("%DIF END PREAMBLE EXTENSION", diff, fixed = TRUE)
stopifnot(length(end) == 1L)
diff <- append(
  diff,
  c(
    "\\renewcommand{\\DIFadd}[1]{#1}",
    "\\renewcommand{\\DIFdel}[1]{}",
    "\\renewcommand{\\DIFdelFL}[1]{}"
  ),
  after = end
)
# a heading whose whole title was deleted would print an empty run-in
# heading (apa7 adds a period); drop the command
diff <- paste(diff, collapse = "\n")
diff <- gsub(
  pattern = paste0(
    "\\\\(?:sub)*(?:section|paragraph)\\*?",
    "\\{\\\\DIFdel(\\{(?:[^{}]|(?1))*\\})\\}"
  ),
  replacement = "",
  x = diff,
  perl = TRUE
)
writeLines(
  c(
    "% Generated by .setup/scripts/latexdiff-submitted.R: do not edit.",
    diff
  ),
  output
)
message("Wrote ", output)
